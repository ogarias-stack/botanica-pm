BEGIN;

CREATE TABLE proyectos (
    id varchar(80) PRIMARY KEY,
    nombre varchar(160) NOT NULL CHECK (btrim(nombre) <> ''),
    fase_actual varchar(40) NOT NULL CHECK (fase_actual IN (
        'Anteproyecto', 'Proyecto Técnico y Permisos', 'Contratación',
        'Ejecución (Obra)', 'Entrega y Cierre'
    )),
    presupuesto_objetivo numeric(16,2) NOT NULL CHECK (presupuesto_objetivo > 0),
    fecha_inicio date NOT NULL DEFAULT CURRENT_DATE,
    revision integer NOT NULL DEFAULT 1 CHECK (revision >= 1),
    cerrado_en timestamptz,
    CHECK (cerrado_en IS NULL OR fase_actual = 'Entrega y Cierre')
);

CREATE UNIQUE INDEX proyectos_nombre_unico ON proyectos (lower(nombre));

CREATE TABLE tareas_fase (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id varchar(80) NOT NULL REFERENCES proyectos(id),
    fase varchar(40) NOT NULL CHECK (fase IN (
        'Anteproyecto', 'Proyecto Técnico y Permisos', 'Contratación',
        'Ejecución (Obra)', 'Entrega y Cierre'
    )),
    descripcion varchar(160) NOT NULL,
    completada boolean NOT NULL DEFAULT false,
    referencia_evidencia varchar(500),
    completada_por text,
    completada_en timestamptz,
    UNIQUE (proyecto_id, fase, descripcion),
    CHECK (
        (completada AND referencia_evidencia IS NOT NULL
            AND btrim(referencia_evidencia) <> ''
            AND completada_por IS NOT NULL AND completada_en IS NOT NULL)
        OR
        (NOT completada AND referencia_evidencia IS NULL
            AND completada_por IS NULL AND completada_en IS NULL)
    )
);

COMMIT;
